#Logical Operators
p = True
q = False
r = p and q  # Logical AND
o = p or q   # Logical OR
n = not p    # Logical NOT
print("Logical AND:", r) # True and False = False, True and True = True, False and False = False
print("Logical OR:", o)  # True or False = True, True or True = True, False or False = False
print("Logical NOT:", n) # not True = False, not False = True

